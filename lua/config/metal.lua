--[[ Metal Shading Language is a C++14 dialect whose scalar and vector builtins
     and feature macros are injected by Apple's metal frontend, so clangd cannot
     parse a shader on its own. It gets a generated prelude declaring those
     builtins and neutering the address-space and function qualifiers, applied
     through clangd's user config under a path condition so C and C++ are
     untouched. Both files are derived from whatever toolchain xcrun resolves
     and are rebuilt when that changes.

     clangd's diagnostics are off for these files. The prelude cannot express
     Metal's variadic vector constructors or its texture template defaults, so
     the errors it reports are largely false. The metal compiler supplies
     diagnostics on write instead. ]]

local assets = vim.fn.stdpath("data") .. "/metal"
local prelude = assets .. "/prelude.h"
local stamp = assets .. "/toolchain"
local clangd_config = vim.fs.normalize("~/Library/Preferences/clangd/config.yaml")
local marker = "# generated by nvim lua/config/metal.lua"

--[[ Scalar aliases the frontend predeclares. These must match metal_types
     exactly: a conflicting typedef aborts that header, taking the whole metal
     namespace with it. ]]
local scalars = {
  { "unsigned char", "uchar" },
  { "unsigned short", "ushort" },
  { "unsigned int", "uint" },
  { "unsigned long", "ulong" },
  { "__fp16", "half" },
}

local vectors = {
  { "bool", "bool" },
  { "char", "char" },
  { "uchar", "uchar" },
  { "short", "short" },
  { "ushort", "ushort" },
  { "int", "int" },
  { "uint", "uint" },
  { "long long", "long" },
  { "unsigned long", "ulong" },
  { "half", "half" },
  { "float", "float" },
}

--[[ Qualifiers with no C++ spelling. Neutered after the headers, which declare
     members of the same names. ]]
local qualifiers = {
  "vertex",
  "fragment",
  "kernel",
  "device",
  "threadgroup",
  "threadgroup_imageblock",
  "thread",
  "ray_data",
  "object_data",
}

local function metal(args)
  local cmd = { "xcrun", "-sdk", "macosx", "metal" }
  vim.list_extend(cmd, args)
  local res = vim.system(cmd, { text = true }):wait()
  return res.code == 0 and res or nil
end

--[[ Apple's metal headers are the entries in the frontend's search list that do
     not come from the macOS SDK; clangd supplies the SDK ones itself. ]]
local function header_dirs()
  local sdk = vim.system({ "xcrun", "--sdk", "macosx", "--show-sdk-path" }, { text = true }):wait()
  local res = metal({ "-x", "metal", "-E", "-v", "-o", "/dev/null", "/dev/null" })
  if sdk.code ~= 0 or not res then
    return nil
  end
  sdk = vim.trim(sdk.stdout)

  local dirs, collecting = {}, false
  for line in res.stderr:gmatch("[^\n]+") do
    if line:find("search starts here:", 1, true) then
      collecting = true
    elseif line:find("End of search list", 1, true) then
      break
    elseif collecting then
      local dir = vim.trim(line)
      if not dir:find("(framework directory)", 1, true) and not vim.startswith(dir, sdk) then
        table.insert(dirs, dir)
      end
    end
  end
  return dirs
end

local function build_prelude()
  local res = metal({ "-x", "metal", "-dM", "-E", "/dev/null" })
  if not res then
    return nil
  end

  local lines = { "/* Generated from the installed Metal toolchain. Do not edit. */", "#pragma once" }
  for line in res.stdout:gmatch("[^\n]+") do
    if vim.startswith(line, "#define __METAL") then
      table.insert(lines, line)
    end
  end

  for _, alias in ipairs(scalars) do
    table.insert(lines, ("typedef %s %s;"):format(alias[1], alias[2]))
  end
  for _, family in ipairs(vectors) do
    for _, width in ipairs({ 2, 3, 4 }) do
      local decl = "typedef %s %s%d __attribute__((ext_vector_type(%d)));"
      table.insert(lines, decl:format(family[1], family[2], width, width))
    end
  end

  table.insert(lines, "#include <metal_stdlib>")
  for _, name in ipairs(qualifiers) do
    table.insert(lines, "#define " .. name)
  end
  table.insert(lines, "#define constant const")
  return lines
end

local function write_clangd_config(dirs)
  local existing = vim.fn.filereadable(clangd_config) == 1
  if existing and not vim.iter(vim.fn.readfile(clangd_config)):any(function(l)
    return l == marker
  end) then
    vim.notify(clangd_config .. " already exists; Metal clangd flags not installed", vim.log.levels.WARN)
    return false
  end

  local flags = { "-x", "c++", "-std=c++17", "-ferror-limit=0", "-include", prelude }
  for _, dir in ipairs(dirs) do
    vim.list_extend(flags, { "-isystem", dir })
  end
  local quoted = vim.tbl_map(function(flag)
    return ("%q"):format(flag)
  end, flags)

  vim.fn.mkdir(vim.fs.dirname(clangd_config), "p")
  vim.fn.writefile({
    marker,
    "If:",
    "  PathMatch: .*\\.metal",
    "CompileFlags:",
    "  Add: [" .. table.concat(quoted, ", ") .. "]",
    "Diagnostics:",
    '  Suppress: "*"',
  }, clangd_config)
  return true
end

local generated = false

local function generate()
  if generated or vim.fn.executable("xcrun") == 0 then
    return
  end
  generated = true

  local found = vim.system({ "xcrun", "--sdk", "macosx", "--find", "metal" }, { text = true }):wait()
  if found.code ~= 0 then
    return
  end
  local toolchain = vim.trim(found.stdout)
  local current = vim.fn.filereadable(stamp) == 1 and vim.fn.readfile(stamp)[1] or nil
  if current == toolchain and vim.fn.filereadable(prelude) == 1 then
    return
  end

  local lines, dirs = build_prelude(), header_dirs()
  if not lines or not dirs or #dirs == 0 then
    return
  end

  vim.fn.mkdir(assets, "p")
  vim.fn.writefile(lines, prelude)
  if write_clangd_config(dirs) then
    vim.fn.writefile({ toolchain }, stamp)
  end
end

local ns = vim.api.nvim_create_namespace("metal")

local severities = {
  error = vim.diagnostic.severity.ERROR,
  warning = vim.diagnostic.severity.WARN,
}

--[[ Diagnostics for the file as saved, so unwritten edits show the previous
     result rather than nothing. ]]
local function check(buf)
  local file = vim.api.nvim_buf_get_name(buf)
  if file == "" or vim.fn.filereadable(file) == 0 then
    return
  end

  local cmd = { "xcrun", "-sdk", "macosx", "metal", "-fsyntax-only", "-I", vim.fs.dirname(file), file }
  vim.system(cmd, { text = true }, function(res)
    vim.schedule(function()
      if not vim.api.nvim_buf_is_valid(buf) then
        return
      end
      local items = {}
      for line in (res.stderr or ""):gmatch("[^\n]+") do
        local path, lnum, col, kind, message = line:match("^(.-):(%d+):(%d+): (%a+): (.+)$")
        if path == file and severities[kind] then
          table.insert(items, {
            lnum = tonumber(lnum) - 1,
            col = tonumber(col) - 1,
            severity = severities[kind],
            message = message,
            source = "metal",
          })
        end
      end
      vim.diagnostic.set(ns, buf, items)
    end)
  end)
end

vim.treesitter.language.register("cpp", "metal")

vim.api.nvim_create_autocmd("FileType", {
  pattern = "metal",
  callback = function(event)
    vim.bo[event.buf].commentstring = "// %s"
    vim.bo[event.buf].cindent = true
    generate()
    check(event.buf)
  end,
})

vim.api.nvim_create_autocmd("BufWritePost", {
  pattern = "*.metal",
  callback = function(event)
    check(event.buf)
  end,
})
